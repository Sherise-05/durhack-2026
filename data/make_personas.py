"""Generates data/personas.json: the four demo personas.

    python data/make_personas.py

Deterministic (fixed seed), so re-running gives the same file. To change a
persona, edit the numbers here and re-run rather than editing the JSON by
hand: synthetic morning ratings are based on a logistic sleep-duration curve
with added noise. Learning now uses direction-only labels, so exact recovery
of these chosen need values is not expected. These are demos, not validation
data. Not imported by the app.
"""
import json, math, random, sys
from pathlib import Path

rng = random.Random(2026)

def hm(h):
    h %= 24
    m = int(round(h * 60 / 5) * 5) % (24 * 60)
    return f"{m // 60:02d}:{m % 60:02d}"

def rating_for(tst, need):
    p = 1 / (1 + math.exp(-(tst - need) / 0.6))
    return max(1, min(5, round(1 + 4 * p + rng.uniform(-0.6, 0.6))))

def night(n, bed, wake, eff, hrv, need, deep=0.18, rem=0.22, awake=2, rhr=58, latency=14):
    in_bed = (wake - bed) % 24
    tst = in_bed * eff
    return {"night": n, "bed": hm(bed), "wake": hm(wake), "efficiency": round(eff, 2),
            "latency_min": latency, "hrv_ms": round(hrv), "deep_pct": round(deep, 2), "rem_pct": round(rem, 2),
            "awakenings": awake, "resting_hr": rhr, "rating": rating_for(tst, need)}

def j(x, s): return x + rng.uniform(-s, s)

